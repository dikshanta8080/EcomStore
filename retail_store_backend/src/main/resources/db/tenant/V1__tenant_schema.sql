CREATE TABLE IF NOT EXISTS units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    symbol VARCHAR(255) NOT NULL,
    unit_type VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uk_units_name UNIQUE (name),
    CONSTRAINT uk_units_symbol UNIQUE (symbol)
);

CREATE TABLE IF NOT EXISTS tax_rates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate NUMERIC(38, 2) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uk_categories_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    sku VARCHAR(255) NOT NULL,
    description VARCHAR(255) NOT NULL,
    price NUMERIC(38, 2) NOT NULL,
    category_id BIGINT NOT NULL,
    base_unit_id BIGINT NOT NULL,
    tax_rate_id BIGINT,
    active BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uk_products_name UNIQUE (name),
    CONSTRAINT uk_products_sku UNIQUE (sku),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT fk_products_base_unit FOREIGN KEY (base_unit_id) REFERENCES units (id),
    CONSTRAINT fk_products_tax_rate FOREIGN KEY (tax_rate_id) REFERENCES tax_rates (id)
);

CREATE TABLE IF NOT EXISTS product_unit_conversions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    unit_id BIGINT NOT NULL,
    conversion_factor NUMERIC(19, 4) NOT NULL,
    active BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uk_product_unit UNIQUE (product_id, unit_id),
    CONSTRAINT fk_puc_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk_puc_unit FOREIGN KEY (unit_id) REFERENCES units (id)
);

CREATE TABLE IF NOT EXISTS inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    stock NUMERIC(19, 4) DEFAULT 0.0000 NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uk_inventory_product UNIQUE (product_id),
    CONSTRAINT fk_inventory_product FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE TABLE IF NOT EXISTS inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_type VARCHAR(255) NOT NULL,
    quantity NUMERIC(19, 4) NOT NULL,
    unit_id BIGINT NOT NULL,
    base_quantity NUMERIC(19, 4) NOT NULL,
    base_unit_id BIGINT NOT NULL,
    conversion_factor NUMERIC(19, 4) NOT NULL,
    unit_price NUMERIC(19, 4) NOT NULL,
    total_amount NUMERIC(19, 4) NOT NULL,
    inventory_id BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT fk_inv_mov_unit FOREIGN KEY (unit_id) REFERENCES units (id),
    CONSTRAINT fk_inv_mov_base_unit FOREIGN KEY (base_unit_id) REFERENCES units (id),
    CONSTRAINT fk_inv_mov_inventory FOREIGN KEY (inventory_id) REFERENCES inventory (id)
);

CREATE TABLE IF NOT EXISTS sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number UUID NOT NULL,
    sub_total NUMERIC(38, 2) NOT NULL,
    discount NUMERIC(38, 2) NOT NULL,
    tax NUMERIC(38, 2) NOT NULL,
    total NUMERIC(38, 2) NOT NULL,
    status VARCHAR(255) DEFAULT 'PENDING' NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uk_sales_invoice_number UNIQUE (invoice_number)
);

CREATE TABLE IF NOT EXISTS sale_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT,
    quantity BIGINT NOT NULL,
    price NUMERIC(38, 2) NOT NULL,
    total NUMERIC(38, 2) NOT NULL,
    tax NUMERIC(38, 2) NOT NULL,
    sale_id BIGINT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT fk_sale_item_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk_sale_item_sale FOREIGN KEY (sale_id) REFERENCES sales (id)
);

CREATE TABLE IF NOT EXISTS payments (
    id UUID PRIMARY KEY,
    total_amount NUMERIC(38, 2) NOT NULL,
    paid_amount NUMERIC(38, 2) DEFAULT 0.00 NOT NULL,
    status VARCHAR(255) DEFAULT 'COMPLETED' NOT NULL,
    sale_id BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_payments_sale FOREIGN KEY (sale_id) REFERENCES sales (id)
);

CREATE TABLE IF NOT EXISTS sub_payments (
    id UUID PRIMARY KEY,
    payment_method VARCHAR(255) NOT NULL,
    amount NUMERIC(38, 2) NOT NULL,
    transaction_id VARCHAR(255),
    status VARCHAR(255) DEFAULT 'COMPLETED' NOT NULL,
    payment_id UUID NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_sub_payment_transaction_method UNIQUE (transaction_id, payment_method),
    CONSTRAINT fk_sub_payments_payment FOREIGN KEY (payment_id) REFERENCES payments (id)
);

CREATE INDEX IF NOT EXISTS idx_products_category_id ON products (category_id);
CREATE INDEX IF NOT EXISTS idx_products_base_unit_id ON products (base_unit_id);
CREATE INDEX IF NOT EXISTS idx_products_tax_rate_id ON products (tax_rate_id);
CREATE INDEX IF NOT EXISTS idx_puc_product_id ON product_unit_conversions (product_id);
CREATE INDEX IF NOT EXISTS idx_puc_unit_id ON product_unit_conversions (unit_id);
CREATE INDEX IF NOT EXISTS idx_inv_mov_inventory_id ON inventory_movements (inventory_id);
CREATE INDEX IF NOT EXISTS idx_inv_mov_unit_id ON inventory_movements (unit_id);
CREATE INDEX IF NOT EXISTS idx_inv_mov_base_unit_id ON inventory_movements (base_unit_id);
CREATE INDEX IF NOT EXISTS idx_sale_item_product_id ON sale_item (product_id);
CREATE INDEX IF NOT EXISTS idx_sale_item_sale_id ON sale_item (sale_id);
CREATE INDEX IF NOT EXISTS idx_payments_sale_id ON payments (sale_id);
CREATE INDEX IF NOT EXISTS idx_sub_payments_payment_id ON sub_payments (payment_id);

